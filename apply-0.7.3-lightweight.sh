#!/usr/bin/env bash
# v0.7.3 lightweight memory fix
# - Ring buffer: 2880→120 (1h only, 24h from CSV)
# - No persistent CSV cache (freed after renderToDisk)
# - renderToDisk every 5 min: 1h+24h only
# - renderSlowToDisk once a day at 4am: 7d+all
# - renderToDisk runs synchronously on startup (static files ready before HTTP)
# Expected memory: ~150MB steady state (was 2.5GB)
set -e

GO_DIR=""
for d in "$PWD" "$PWD/dashboard/bin/go" "$(dirname "$0")" "/root/bpftune/dashboard/bin/go" "$HOME/bpftune/dashboard/bin/go"; do
  if [[ -f "$d/go.mod" && -f "$d/main.go" ]]; then GO_DIR="$d"; break; fi
done
if [[ -z "$GO_DIR" ]]; then echo 'ERROR: cd into bpftune/dashboard/bin/go first'; exit 1; fi
echo "Go src: $GO_DIR"

GO_BIN=go
command -v $GO_BIN >/dev/null || GO_BIN=/usr/local/go/bin/go
echo "Go: $GO_BIN"

STAGE=$(mktemp -d)
sed -n '/^__SRC_BEGIN__$/,/^__SRC_END__$/p' "$0" | sed -e '1d' -e '$d' | base64 -d | tar -xzf - -C "$STAGE"

BACKUP="$GO_DIR.bak.v0.7.3.$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"
cp -a "$GO_DIR"/*.go "$BACKUP"/ 2>/dev/null || true
echo "Backup: $BACKUP"

for f in history.go csv_reader.go render.go http_handlers.go main.go; do
  cp "$STAGE/$f" "$GO_DIR/$f.tmp" && mv "$GO_DIR/$f.tmp" "$GO_DIR/$f"
done
rm -rf "$STAGE"

cd "$GO_DIR"
$GO_BIN fmt . 2>&1 || true
if ! $GO_BIN build -o bpftune-collector-go .; then
  echo 'BUILD FAILED — restoring backup'
  cp -a "$BACKUP"/*.go "$GO_DIR"/
  exit 1
fi
echo 'Build OK'

systemctl stop bpftune-collector-go 2>/dev/null || true
cp bpftune-collector-go /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
chmod +x /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
rm -f /var/lib/bpftune/history/data/*.json
systemctl start bpftune-collector-go
sleep 20
systemctl status bpftune-collector-go --no-pager | head -12
exit 0

