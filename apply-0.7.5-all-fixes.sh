#!/usr/bin/env bash
# v0.7.5 — fixes ALL remaining issues:
# 1. 30d chart = 0 → FIXED: added "30d" to switch case
# 2. Proof leaderboard empty → FIXED: proofs_raw now returns per-event data with dest field
# 3. Coverage 0% → FIXED: compute rate_best_v in CSV writer (was always "0")
# 4. "(120)" and "(custom)" display → FIXED: removed from dashboard.js dropdown
set -e

GO_DIR=""
for d in "$PWD" "$PWD/dashboard/bin/go" "/root/bpftune/dashboard/bin/go" "$HOME/bpftune/dashboard/bin/go"; do
  if [[ -f "$d/go.mod" && -f "$d/main.go" ]]; then GO_DIR="$d"; break; fi
done
if [[ -z "$GO_DIR" ]]; then echo 'ERROR: cd into bpftune/dashboard/bin/go first'; exit 1; fi
echo "Go src: $GO_DIR"

GO_BIN=go
command -v $GO_BIN >/dev/null 2>/dev/null || GO_BIN=/usr/local/go/bin/go

# Decode Go source files
STAGE=$(mktemp -d)
sed -n '/^__GO_BEGIN__$/,/^__GO_END__$/p' "$0" | sed -e '1d' -e '$d' | base64 -d | tar -xzf - -C "$STAGE"

BACKUP="$GO_DIR.bak.v0.7.5.$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"
cp -a "$GO_DIR"/*.go "$BACKUP"/ 2>/dev/null || true
echo "Backup: $BACKUP"

for f in render.go http_handlers.go csv_writer.go log_parsing.go collect.go; do
  cp "$STAGE/$f" "$GO_DIR/$f.tmp" && mv "$GO_DIR/$f.tmp" "$GO_DIR/$f"
done
rm -rf "$STAGE"

# Also patch dashboard.js (remove (120) and (custom) suffixes)
DASH_JS="/opt/bpftune-dashboard/bin/dashboard.js"
if [[ -f "$DASH_JS" ]]; then
  cp "$DASH_JS" "$BACKUP/dashboard.js.bak"
  # Remove (' + b.points + ') suffix
  sed -i "s/' (' + b.points + ')<\/option>'/'<\/option>'/g" "$DASH_JS"
  # Remove (custom) suffix
  sed -i "s/' (custom)<\/option>'/'<\/option>'/g" "$DASH_JS"
  echo "Patched dashboard.js"
fi

cd "$GO_DIR"
$GO_BIN fmt . 2>&1 || true
if ! $GO_BIN build -o bpftune-collector-go .; then
  echo 'BUILD FAILED — restoring backup'
  cp -a "$BACKUP"/*.go "$GO_DIR"/
  exit 1
fi
echo 'Build OK'

systemctl stop bpftune-collector-go 2>/dev/null || true
cp bpftune-collector-go /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
chmod +x /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
rm -f /var/lib/bpftune/history/data/*.json
systemctl start bpftune-collector-go
sleep 30
systemctl status bpftune-collector-go --no-pager | head -12
exit 0

