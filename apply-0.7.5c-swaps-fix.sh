#!/usr/bin/env bash
# v0.7.5c — swaps per bin now reads from swaps.csv (full history) + aligned with ts array
# Fixes: swaps per bin chart now matches other charts time range
set -e

GO_DIR=""
for d in "$PWD" "$PWD/dashboard/bin/go" "/root/bpftune/dashboard/bin/go" "$HOME/bpftune/dashboard/bin/go"; do
  if [[ -f "$d/go.mod" && -f "$d/main.go" ]]; then GO_DIR="$d"; break; fi
done
if [[ -z "$GO_DIR" ]]; then echo "ERROR: cd into bpftune/dashboard/bin/go first"; exit 1; fi
echo "Go src: $GO_DIR"

GO_BIN=go
command -v $GO_BIN >/dev/null 2>/dev/null || GO_BIN=/usr/local/go/bin/go

STAGE=$(mktemp -d)
sed -n "/^__GO_BEGIN__$/,/^__GO_END__$/p" "$0" | sed -e "1d" -e "\$d" | base64 -d | tar -xzf - -C "$STAGE"
cp "$STAGE/render.go" "$GO_DIR/render.go.tmp" && mv "$GO_DIR/render.go.tmp" "$GO_DIR/render.go"
rm -rf "$STAGE"

cd "$GO_DIR"
$GO_BIN fmt . 2>&1 || true
if ! $GO_BIN build -o bpftune-collector-go .; then echo "BUILD FAILED"; exit 1; fi
echo "Build OK"

systemctl stop bpftune-collector-go 2>/dev/null || true
cp bpftune-collector-go /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
chmod +x /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
rm -f /var/lib/bpftune/history/data/*.json
systemctl start bpftune-collector-go
sleep 30
systemctl status bpftune-collector-go --no-pager | head -12
exit 0

