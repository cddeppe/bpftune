#!/usr/bin/env bash
# v0.7.2 memory fix — replace 5 maps per snapshot with 16-element arrays
# Cuts memory from ~2.3GB to ~200MB on 104-bucket hosts
set -e

# Find the Go source dir
GO_DIR=""
for d in "$PWD" "$PWD/dashboard/bin/go" "$(dirname "$0")" "/root/bpftune/dashboard/bin/go" "$HOME/bpftune/dashboard/bin/go"; do
  if [[ -f "$d/go.mod" ]]; then GO_DIR="$d"; break; fi
done
if [[ -z "$GO_DIR" ]]; then
  echo "ERROR: could not find Go source dir (looking for go.mod)"
  echo "cd into your bpftune/dashboard/bin/go dir first, or pass the path"
  exit 1
fi
echo "Go src: $GO_DIR"

# Find Go binary
GO_BIN=""
for g in go /usr/local/go/bin/go /home/z/go-install/go/bin/go /usr/lib/go/bin/go; do
  if command -v "$g" &>/dev/null || [[ -x "$g" ]]; then GO_BIN="$g"; break; fi
done
if [[ -z "$GO_BIN" ]]; then
  echo "ERROR: Go not installed. Install: sudo apt-get install -y golang-go"
  exit 1
fi
echo "Go: $GO_BIN"

# Decode embedded source files
STAGE=$(mktemp -d)
sed -n '/^__SRC_BEGIN__$/,/^__SRC_END__$/p' "$0" | \
  sed -e '1d' -e '$d' | base64 -d | tar -xzf - -C "$STAGE"

# Backup + deploy
BACKUP="$GO_DIR.bak.v0.7.2.$(date +%Y%m%d-%H%M%S)"
mkdir -p "$BACKUP"
cp -a "$GO_DIR"/*.go "$BACKUP"/ 2>/dev/null || true
echo "Backup: $BACKUP"

# Write files (atomic per-file)
for f in history.go render.go collect.go csv_reader.go http_handlers.go; do
  cp "$STAGE/$f" "$GO_DIR/$f.tmp" && mv "$GO_DIR/$f.tmp" "$GO_DIR/$f"
done
rm -rf "$STAGE"

# Build
cd "$GO_DIR"
$GO_BIN fmt . 2>&1 || true
if ! $GO_BIN build -o bpftune-collector-go .; then
  echo "BUILD FAILED — restoring backup"
  cp -a "$BACKUP"/*.go "$GO_DIR"/
  exit 1
fi
echo "Build OK"

# Deploy + restart
systemctl stop bpftune-collector-go 2>/dev/null || true
cp bpftune-collector-go /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
chmod +x /opt/bpftune-dashboard/bin/bpftune-collector-go 2>/dev/null || true
rm -f /var/lib/bpftune/history/data/*.json  # clear stale static files
systemctl start bpftune-collector-go
sleep 15
systemctl status bpftune-collector-go --no-pager | head -12
exit 0

